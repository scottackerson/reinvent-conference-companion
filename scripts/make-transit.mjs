// Monorail and free tram lines for the map: node scripts/make-transit.mjs [events/reinvent-2026]
// Asks the Overpass API for monorail and tram (funicular) lines and their stops around the Strip and writes
// transit.json next to event.json. The bounding box and the tram names below are Las Vegas specific.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { UA, r5, sleep, simplify } from './lib-geo.mjs';

const dir = process.argv[2] || 'events/reinvent-2026';
const BBOX = '36.08,-115.19,36.15,-115.14';
const TRAMS = { 'Mandalay Bay Tram': 'Mandalay Bay tram', 'Mandalay Bay Tram Express': 'Mandalay Bay tram', 'Aria Express': 'Aria Express tram' };
const q = `[out:json][timeout:90];(way["railway"~"monorail|funicular"](${BBOX});node["railway"~"stop|tram_stop"](${BBOX}););out geom tags;`;
const SERVERS = ['https://overpass-api.de/api/interpreter', 'https://overpass.private.coffee/api/interpreter'];
let j = null;
for (let i = 0; i < 10 && !j; i++) {
  for (const s of SERVERS) {
    try {
      const res = await fetch(s, { method: 'POST', headers: { 'User-Agent': UA, 'Content-Type': 'application/x-www-form-urlencoded' }, body: 'data=' + encodeURIComponent(q) });
      const t = await res.text();
      if (t.startsWith('{')) { j = JSON.parse(t); break; }
    } catch (e) { /* try the next server */ }
  }
  if (!j) { console.log('Overpass busy, retrying in 30 s'); await sleep(30000); }
}
if (!j) { console.error('Overpass did not answer. Try again later.'); process.exit(1); }

const ways = j.elements.filter(e => e.type === 'way');
const seg = w => simplify(w.geometry.map(g => [r5(g.lon), r5(g.lat)]));
const lines = [{ id: 'monorail', name: 'Las Vegas Monorail', kind: 'monorail', lines: ways.filter(w => w.tags.railway === 'monorail' && !w.tags.service).map(seg) }];
for (const name of new Set(Object.values(TRAMS))) {
  lines.push({ id: name.toLowerCase().replace(/[^a-z]+/g, '-').replace(/-$/, ''), name, kind: 'tram', lines: ways.filter(w => w.tags.railway === 'funicular' && TRAMS[w.tags.name] === name).map(seg) });
}
const group = {};
const add = (name, kind, e) => { const k = `${kind}|${name}`; (group[k] = group[k] || []).push([e.lon, e.lat]); };
for (const e of j.elements) {
  if (e.type !== 'node' || !e.tags.name) continue;
  if (e.tags.railway === 'stop' && e.tags.monorail === 'yes') add(e.tags.name.replace("Caesar's", 'Caesars'), 'monorail', e);
  if (e.tags.railway === 'tram_stop') add(e.tags.name.replace(/ Tram Station$/, '').replace(/ (Main|North Express|North|Express)$/, ''), 'tram', e);
}
const avg = (ps, i) => r5(ps.reduce((s, p) => s + p[i], 0) / ps.length);
const stations = Object.entries(group).map(([k, ps]) => { const [kind, name] = k.split('|'); return { name: `${name} ${kind}`, kind, geo: [avg(ps, 0), avg(ps, 1)] }; });
const out = { source: 'OpenStreetMap contributors (ODbL), via the Overpass API', checked: new Date().toISOString().slice(0, 10), _note: 'Generated by scripts/make-transit.mjs. Do not draw by hand.', lines, stations };
writeFileSync(join(dir, 'transit.json'), JSON.stringify(out) + '\n');
console.log(lines.map(l => `${l.name}: ${l.lines.length} segments`).join('\n') + `\n${stations.length} stations`);
