// Walking paths for the map: node scripts/make-routes.mjs [events/reinvent-2026]
// Reads venue and hotel coordinates (geo) from event.json and asks the OpenStreetMap foot router
// (routing.openstreetmap.de, one request a second) for a path between every pair of venues and from every
// pack hotel to every venue. Writes routes.json next to event.json. Paths follow streets and mapped
// walkways; casino interiors are often missing from the map, so treat them as approximate.
// The minutes on screen still come from travelTimes in event.json; the script prints both to compare.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { UA, r5, sleep, simplify } from './lib-geo.mjs';

const dir = process.argv[2] || 'events/reinvent-2026';
const pack = JSON.parse(readFileSync(join(dir, 'event.json'), 'utf8'));
const places = {};
for (const v of pack.venues) if (v.geo) places[v.id] = v.geo;
for (const h of pack.hotels) if (h.geo && !h.venueId) places[`hotel:${h.id}`] = h.geo;
const venueIds = pack.venues.filter(v => v.geo).map(v => v.id);
const pairs = new Set();
for (const a of Object.keys(places)) for (const b of venueIds) if (a !== b) pairs.add([a, b].sort().join('|'));

const routes = {};
for (const key of [...pairs].sort()) {
  const [a, b] = key.split('|');
  const url = `https://routing.openstreetmap.de/routed-foot/route/v1/foot/${places[a].join(',')};${places[b].join(',')}?overview=full&geometries=geojson`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  const j = await res.json();
  if (j.code !== 'Ok') { console.log(`skip ${key}: ${j.code}`); continue; }
  const r = j.routes[0];
  const line = simplify(r.geometry.coordinates.map(([x, y]) => [r5(x), r5(y)]));
  routes[key] = { meters: Math.round(r.distance), walkMin: Math.round(r.duration / 60), line };
  const tt = pack.travelTimes || {};
  const table = a.startsWith('hotel:') ? (pack.hotels.find(h => `hotel:${h.id}` === a).minutesTo || {})[b] : (tt[a] || {})[b] ?? (tt[b] || {})[a];
  console.log(`${key.padEnd(28)} ${String(Math.round(r.distance)).padStart(5)} m  router ${String(Math.round(r.duration / 60)).padStart(3)} min  table ${table ?? '-'} min`);
  await sleep(1100);
}
const out = { source: 'OpenStreetMap contributors (ODbL), foot routing by routing.openstreetmap.de (FOSSGIS)', checked: new Date().toISOString().slice(0, 10), _note: 'Generated by scripts/make-routes.mjs. Paths are approximate; minutes on screen come from travelTimes in event.json.', routes };
writeFileSync(join(dir, 'routes.json'), JSON.stringify(out) + '\n');
console.log(`wrote ${Object.keys(routes).length} routes to ${join(dir, 'routes.json')}`);
